function [field,audit]=mf12_eta20_reference( ...
        eta11_spectrum,kx,ky,depth,mf12_root)
source_file=fullfile(mf12_root,'mf12_spectral_coefficients.m');
if ~isfile(source_file),error('Official MF12 source not found: %s',source_file);end
addpath(mf12_root,'-begin');
resolved=string(which('mf12_spectral_coefficients'));
if ~strcmpi(char(resolved),char(source_file))
    error('Unexpected MF12 source resolved: %s',resolved);
end
positive=kx>0;
threshold=1e-13*max(1,max(abs(eta11_spectrum),[],'all'));
parent_indices=find(positive & abs(eta11_spectrum)>threshold);
grid_count=numel(eta11_spectrum);
coefficients_eta=eta11_spectrum(parent_indices)/grid_count;
a=2*real(coefficients_eta);b=2*imag(coefficients_eta);
timer=tic;
coefficients=mf12_spectral_coefficients(2,1.0,depth,a,b, ...
    kx(parent_indices),ky(parent_indices),0.0,0.0);
difference_indices=2:2:numel(coefficients.G_npm);
values=(coefficients.A_npm(difference_indices) ...
    +1i*coefficients.B_npm(difference_indices)) ...
    .*coefficients.G_npm(difference_indices);
delta_kx=kx(1,2)-kx(1,1);delta_ky=ky(2,1)-ky(1,1);
n=size(eta11_spectrum,1);
columns=mod(round(coefficients.kx_npm(difference_indices)/delta_kx),n)+1;
rows=mod(round(coefficients.ky_npm(difference_indices)/delta_ky),n)+1;
one_sided=accumarray([rows(:),columns(:)],values(:),[n n],@sum,complex(0));
one_sided(1,1)=0;
field=real(ifft2(one_sided))*grid_count;
audit=struct('total_seconds',toc(timer), ...
    'active_positive_parent_count',numel(parent_indices), ...
    'strict_zero_mode','set-to-zero-separate-sector', ...
    'external_source',resolved);
end

function cb=field_image(ax,x,field,limit,display_window,title_text,show_colorbar)
imagesc(ax,x,x,field);axis(ax,'xy','equal','tight');
clim(ax,[-limit limit]);colormap(ax,redblue_map(256));
xlim(ax,display_window*[-1,1]);ylim(ax,display_window*[-1,1]);
xlabel(ax,'$x/\lambda_p$');
if show_colorbar
    cb=colorbar(ax);cb.FontName='CMU Serif';cb.TickLabelInterpreter='latex';
else
    cb=gobjects(0);
end
ylabel(ax,'$y/\lambda_p$');title(ax,title_text,'FontWeight','normal');
end

function line_style(ax,x_limits,y_limits,title_text,y_text)
grid(ax,'on');box(ax,'on');xlim(ax,x_limits);ylim(ax,y_limits);
xlabel(ax,'$x/\lambda_p$ at $y/\lambda_p=0$');ylabel(ax,y_text);
title(ax,title_text,'FontWeight','normal');
end

