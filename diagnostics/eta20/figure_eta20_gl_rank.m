    max(abs(difference12),[],'all');max(abs(difference16),[],'all'); ...
    max(abs(difference_band),[],'all')] ...
    /reference_peak;
norm_ratios=[candidate6_norm;candidate12_norm;candidate16_norm; ...
    candidate_band_norm]/reference_norm;
q_values=[q6;q12;q16;q_band];
cutoffs=[NaN;NaN;NaN;low_output_cutoff];
low_scales=[NaN;NaN;NaN;audit_low.quadrature_scale];
metrics=table(method,repmat(depth,4,1), ...
    repmat(config.crossing_angle_deg,4,1),repmat(config.spread_deg,4,1), ...
    repmat(n,4,1),repmat(reference_audit.active_positive_parent_count,4,1), ...
    ranks,raw_l2_pct,raw_linf_pct,norm_ratios,q_values,cutoffs,low_scales, ...
    'VariableNames',{'method','peak_kpd','crossing_angle_deg','spread_deg', ...
    'grid_size','selected_component_count','quadrature_rank', ...
    'physical_raw_relative_l2_pct','physical_raw_relative_linf_pct', ...
    'candidate_over_mf12_norm_ratio','surface_similarity_Q', ...
    'low_output_cutoff_k_over_k0','low_quadrature_scale'});
