function output_path=figure_eta20_gl_rank( ...
        figure_root,mf12_root,peak_kh)
%FIGURE_ETA20_GL_RANK Matched GL6/GL12/GL16 eta20 comparison.
% Reconstructs the Figure-2 120-degree crossing input at k_p d=1 and compares
% shared GL6/GL12/GL16 with the official finite-component MF12 field.
arguments
    figure_root (1,1) string = string(fullfile('results','paper'))
    mf12_root (1,1) string = string(getenv('MF12_ROOT'))
    peak_kh (1,1) double {mustBePositive,mustBeFinite} = 1
end
if ~isfolder(figure_root),mkdir(figure_root);end
project_root=string(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(fullfile(project_root,'diagnostics','eta20'));
addpath(fullfile(project_root,'diagnostics','eta20','generated'));
addpath(fullfile(project_root,'paper','internal'));
setup_green_laplace("MF12Root",mf12_root);
mf12_source=string(fileparts(which('mf12_spectral_coefficients')));

config=struct('retained_mass_percent',99,'jonswap_gamma',3.3, ...
    'spread_deg',30,'crossing_angle_deg',120,'peak_kh',peak_kh, ...
    'domain_wavelengths',10,'grid_size',256,'auto_expand_grid',true, ...
    'selection_mode','nested-energy','maximum_components',2500, ...
    'radial_bins',48,'angular_bins',96,'minimum_k_over_kp',0.3, ...
    'maximum_k_over_kp',3.5,'crest_amplitude',0.1, ...
    'time_peak_periods',0,'minimum_output_midpoint_q',0.3);
if abs(peak_kh-1)<1e-12
    asset_base="fig_eta20_gl6_gl12_gl16_waveform";
else
    asset_base="fig_eta20_gl6_gl12_gl16_waveform_kph" ...
        +replace(sprintf('%.3g',peak_kh),'.','p');
end
state=generate_eta22_input(config);
eta11_spectrum=state.eta11_spectrum;
kx=state.kx;ky=state.ky;depth=state.depth;
n=size(eta11_spectrum,1);domain_wavelengths=config.domain_wavelengths;
[reference,reference_audit]=mf12_eta20_reference( ...
    eta11_spectrum,kx,ky,depth,mf12_source);
[candidate6_half,audit6]=eta20_green_laplace_shared( ...
    eta11_spectrum,kx,ky,depth,"shared6",project_root);
[candidate12_half,audit12]=eta20_green_laplace_shared( ...
    eta11_spectrum,kx,ky,depth,"shared12",project_root);
[candidate16_half,audit16]=eta20_green_laplace_shared( ...
    eta11_spectrum,kx,ky,depth,"shared16",project_root);
low_output_cutoff=0.3;
[candidate_low_half,audit_low]=eta20_green_laplace_shared( ...
    eta11_spectrum,kx,ky,depth,"endpoint6",project_root);
candidate6=2*candidate6_half;candidate12=2*candidate12_half;
candidate16=2*candidate16_half;
candidate_low=2*candidate_low_half;
output_k_over_k0=hypot(kx,ky);
low_mask=output_k_over_k0>0 & output_k_over_k0<=low_output_cutoff+64*eps;
zero_mask=output_k_over_k0==0;
candidate_band_hat=fft2(candidate6);
candidate_low_hat=fft2(candidate_low);
candidate_band_hat(low_mask)=candidate_low_hat(low_mask);
candidate_band_hat(zero_mask)=0;
candidate_band=real(ifft2(candidate_band_hat));
if ~strcmp(audit6.information_boundary,'eta11-only') ...
        || ~strcmp(audit12.information_boundary,'eta11-only') ...
        || ~strcmp(audit16.information_boundary,'eta11-only') ...
        || ~strcmp(audit_low.information_boundary,'eta11-only')
    error('The post-freeze reference/candidate information boundary failed.');
end
reference_peak=max(abs(reference),[],'all');
reference_norm=norm(reference(:));
difference6=candidate6-reference;difference12=candidate12-reference;
difference16=candidate16-reference;
difference_band=candidate_band-reference;
candidate6_norm=norm(candidate6(:));candidate12_norm=norm(candidate12(:));
candidate16_norm=norm(candidate16(:));
candidate_band_norm=norm(candidate_band(:));
difference6_norm=norm(difference6(:));difference12_norm=norm(difference12(:));
difference16_norm=norm(difference16(:));
difference_band_norm=norm(difference_band(:));
q6=difference6_norm/(reference_norm+candidate6_norm);
q12=difference12_norm/(reference_norm+candidate12_norm);
q16=difference16_norm/(reference_norm+candidate16_norm);
q_band=difference_band_norm/(reference_norm+candidate_band_norm);
method=["GL6";"GL12";"GL16";"GL6 endpoint-band"];ranks=[6;12;16;6];
raw_l2_pct=100*[difference6_norm;difference12_norm;difference16_norm; ...
    difference_band_norm] ...
    /reference_norm;
