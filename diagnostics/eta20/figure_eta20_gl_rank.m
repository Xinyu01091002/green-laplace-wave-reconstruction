    {candidate6,candidate12,candidate16,candidate_band}, ...
    ["GL6","GL12","GL16","GL6 endpoint-band"],kx,ky);
writetable(low_mode_table(low_mode_table.method~="GL6 endpoint-band",:), ...
    fullfile(figure_root, ...
    asset_base+"_low_mode_diagnostic.csv"));
writetable(low_mode_table(low_mode_table.method=="GL6 endpoint-band",:), ...
    fullfile(figure_root,asset_base+"_endpoint_band_low_mode_diagnostic.csv"));

carrier_wavenumber=1;
field_scale=config.crest_amplitude^2*carrier_wavenumber;
x=(-n/2:n/2-1)*domain_wavelengths/n;
reference_normalized=fftshift(reference)/field_scale;
candidate6_normalized=fftshift(candidate6)/field_scale;
candidate12_normalized=fftshift(candidate12)/field_scale;
candidate16_normalized=fftshift(candidate16)/field_scale;
candidate_band_normalized=fftshift(candidate_band)/field_scale;
difference6_percent=100*(candidate6_normalized-reference_normalized) ...
    /max(abs(reference_normalized),[],'all');
difference12_percent=100*(candidate12_normalized-reference_normalized) ...
    /max(abs(reference_normalized),[],'all');
difference16_percent=100*(candidate16_normalized-reference_normalized) ...
    /max(abs(reference_normalized),[],'all');
difference_band_percent=100*(candidate_band_normalized-reference_normalized) ...
    /max(abs(reference_normalized),[],'all');
center=n/2+1;
centerlines=table(x(:),reference_normalized(center,:).', ...
    candidate6_normalized(center,:).',candidate12_normalized(center,:).', ...
    candidate16_normalized(center,:).',difference6_percent(center,:).', ...
    difference12_percent(center,:).',difference16_percent(center,:).', ...
    'VariableNames',{'x_over_lambda_p','mf12_eta20_scaled', ...
    'gl6_eta20_scaled','gl12_eta20_scaled','gl16_eta20_scaled', ...
    'gl6_difference_pct_of_mf12_peak','gl12_difference_pct_of_mf12_peak', ...
    'gl16_difference_pct_of_mf12_peak'});
writetable(centerlines,fullfile(figure_root,asset_base+"_centerline.csv"));
endpoint_centerline=table(x(:),candidate_band_normalized(center,:).', ...
    difference_band_percent(center,:).', ...
    'VariableNames',{'x_over_lambda_p','gl6_endpoint_band_eta20_scaled', ...
    'gl6_endpoint_band_difference_pct_of_mf12_peak'});
writetable(endpoint_centerline,fullfile(figure_root, ...
    asset_base+"_endpoint_band_centerline.csv"));

mode_axis=0:n/2;
kx_over_k0=mode_axis/domain_wavelengths;
reference_center_spectrum=abs(fft(reference_normalized(center,:)))/n;
candidate6_center_spectrum=abs(fft(candidate6_normalized(center,:)))/n;
candidate12_center_spectrum=abs(fft(candidate12_normalized(center,:)))/n;
candidate16_center_spectrum=abs(fft(candidate16_normalized(center,:)))/n;
reference_center_spectrum=reference_center_spectrum(1:n/2+1);
candidate6_center_spectrum=candidate6_center_spectrum(1:n/2+1);
candidate12_center_spectrum=candidate12_center_spectrum(1:n/2+1);
candidate16_center_spectrum=candidate16_center_spectrum(1:n/2+1);
spectrum_table=table(kx_over_k0(:), ...
    reference_center_spectrum(:),candidate6_center_spectrum(:), ...
    candidate12_center_spectrum(:),candidate16_center_spectrum(:), ...
    'VariableNames',{'abs_kx_over_k0','mf12_eta20_spectrum_scaled', ...
    'gl6_eta20_spectrum_scaled','gl12_eta20_spectrum_scaled', ...
    'gl16_eta20_spectrum_scaled'});
writetable(spectrum_table,fullfile(figure_root, ...
    asset_base+"_centerline_spectrum.csv"));

display_window=1.5;
field_limit=max(abs([reference_normalized(:);candidate6_normalized(:); ...
    candidate12_normalized(:);candidate16_normalized(:)]));
difference_limit=max(abs([difference6_percent(:);difference12_percent(:); ...
    difference16_percent(:)]));
line_limit=max(abs([reference_normalized(center,:), ...
    candidate6_normalized(center,:),candidate12_normalized(center,:), ...
    candidate16_normalized(center,:)]));
difference_line_limit=max(abs([difference6_percent(center,:), ...
    difference12_percent(center,:),difference16_percent(center,:)]));
blue=[0.0000 0.4470 0.7410];purple=[0.4940 0.1840 0.5560];
green=[0.4660 0.6740 0.1880];orange=[0.8500 0.3250 0.0980];
