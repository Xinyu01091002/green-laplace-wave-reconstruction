function map=redblue_map(n)
half=floor(n/2);
map=[linspace(0.15,1,half).',linspace(0.35,1,half).',ones(half,1); ...
    ones(n-half,1),linspace(1,0.25,n-half).',linspace(1,0.15,n-half).'];
end

function result=low_mode_diagnostics(reference,candidates,methods,kx,ky)
% Parseval-equivalent full-field Q after excluding low output wave numbers.
thresholds=[0,0.1,0.2,0.3,0.5,1.0];
output_k_over_k0=hypot(kx,ky);n=numel(reference);
reference_hat=fft2(reference);
reference_zero=abs(reference_hat(1,1))/n;
records=struct([]);cursor=0;
for method_index=1:numel(candidates)
    candidate_hat=fft2(candidates{method_index});
    difference_hat=candidate_hat-reference_hat;
    full_q=norm(difference_hat(:)) ...
        /(norm(reference_hat(:))+norm(candidate_hat(:)));
    total_error_energy=sum(abs(difference_hat(:)).^2);
    total_reference_energy=sum(abs(reference_hat(:)).^2);
    for threshold=thresholds
        cursor=cursor+1;
        inside=output_k_over_k0<=threshold+64*eps;
        outside=~inside;
        outside_denominator=norm(reference_hat(outside)) ...
            +norm(candidate_hat(outside));
        if outside_denominator==0
            q_outside=NaN;
        else
            q_outside=norm(difference_hat(outside))/outside_denominator;
        end
        record=struct('method',methods(method_index), ...
            'excluded_k_over_k0_max',threshold, ...
            'excluded_bin_count',nnz(inside), ...
            'reference_zero_mode_amplitude',reference_zero, ...
            'candidate_zero_mode_amplitude',abs(candidate_hat(1,1))/n, ...
            'full_field_Q',full_q,'Q_outside_excluded_region',q_outside, ...
            'error_energy_inside_fraction', ...
                sum(abs(difference_hat(inside)).^2)/total_error_energy, ...
            'reference_energy_inside_fraction', ...
                sum(abs(reference_hat(inside)).^2)/total_reference_energy);
        if cursor==1,records=record;else,records(cursor)=record;end
    end
end
result=struct2table(records);
end
